  /** Как готовимся заранее, чтобы удар был слабее. */
  measures?: string;
  /** План Б: что делаем в первые дни, если угроза наступила. */
  plan?: string;
  note?: string;
  /** Свои слова для подбора новостей (через запятую). Пусто — берутся слова типовой угрозы или категории. */

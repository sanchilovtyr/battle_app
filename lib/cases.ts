/** Первый кейс, релевантный указанному типу бизнеса (ключ из lib/questions.ts).
 *  Возвращает undefined, если подходящего кейса нет (например, "online_edu") —
 *  в этом случае компонент-обёртка просто не рендерится, общий список кейсов
 *  на лендинге всё равно виден. */
export function findCaseForBusinessType(businessType?: string | null): CaseStudy | undefined {
  if (!businessType) return undefined;
  return CASES.find((c) => c.businessTypes.includes(businessType));
}

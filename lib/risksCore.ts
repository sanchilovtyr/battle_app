export function risksForBusiness(businessType: string | undefined): RiskTemplate[] {
  const byKey = businessType ? (NICHE_RISKS as Record<string, RiskTemplate[]>)[businessType] : undefined;
  // В карточке бизнеса тип мог сохраниться подписью («Услуги»), а не ключом — сверяем и по подписи
  const key = byKey ? businessType : (Object.keys(BUSINESS_TYPE_LABELS) as BusinessType[]).find((k) => BUSINESS_TYPE_LABELS[k] === businessType);
  const niche = (key && (NICHE_RISKS as Record<string, RiskTemplate[]>)[key]) || NICHE_RISKS.other;
  return [...UNIVERSAL_RISKS, ...niche];
}

export function findTemplate(id: string, businessType?: string): RiskTemplate | undefined {
  return risksForBusiness(businessType).find((x) => x.id === id) ?? UNIVERSAL_RISKS.find((x) => x.id === id);
}


// ───────────────────────── оценка ─────────────────────────

export const clampScale = (n: unknown): number => {
  const v = Math.round(Number(n));
  return Number.isFinite(v) ? Math.max(1, Math.min(5, v)) : 3;
};

export function clampPeriod(n: unknown): number {
  const v = Number(n);
  return REVIEW_PERIODS.includes(v) ? v : DEFAULT_REVIEW_DAYS;
}

export function riskScore(r: Pick<Risk, "probability" | "impact">): number {
  return clampScale(r.probability) * clampScale(r.impact);
}

export function riskLevel(score: number): RiskLevel {
  return score >= 15 ? "high" : score >= 8 ? "medium" : "low";
}

const DAY = 86400000;

export function dateInDays(from: Date, days: number): string {
  return new Date(from.getTime() + days * DAY).toISOString().slice(0, 10);
}

const today = (now: Date) => now.toISOString().slice(0, 10);

/** Срок проверки уже прошёл. */
export function isReviewDue(r: Risk, now: Date): boolean {
  if (r.status === "controlled" || !r.reviewAt) return false;
  return r.reviewAt < today(now);
}

/** Проверить нужно в ближайшую неделю (или уже пора). */
export function isCheckSoon(r: Risk, now: Date): boolean {
  if (r.status === "controlled" || !r.reviewAt) return false;
  return r.reviewAt <= dateInDays(now, SOON_DAYS);
}

export interface RiskSummary {
  total: number;
  high: number;
  medium: number;
  low: number;
  /** Высокие и средние риски, по которым нет ни подготовки, ни плана Б. */
  noPlan: number;
  reviewDue: number;
  controlled: number;
  /** Не закрытые риски, самые опасные первыми. */
  top: Risk[];
  /** Риски, которые пора проверить, самые просроченные первыми. */
  checkSoon: Risk[];
}

export function summarizeRisks(risks: Risk[], now: Date): RiskSummary {
  const active = risks.filter((r) => r.status !== "controlled");
  const lvl = (r: Risk) => riskLevel(riskScore(r));
  const sorted = [...active].sort((a, b) => riskScore(b) - riskScore(a) || a.title.localeCompare(b.title, "ru"));
  return {
    total: risks.length,
    high: active.filter((r) => lvl(r) === "high").length,
    medium: active.filter((r) => lvl(r) === "medium").length,
    low: active.filter((r) => lvl(r) === "low").length,
    noPlan: active.filter((r) => lvl(r) !== "low" && !(r.measures ?? "").trim() && !(r.plan ?? "").trim()).length,
    reviewDue: active.filter((r) => isReviewDue(r, now)).length,
    controlled: risks.length - active.length,
    top: sorted.slice(0, 3),
    checkSoon: active.filter((r) => isCheckSoon(r, now)).sort((a, b) => (a.reviewAt ?? "").localeCompare(b.reviewAt ?? "")),
  };
}

/** Тепловая карта 5×5: grid[impact-1][probability-1] = число не закрытых рисков в клетке. */
export function heatGrid(risks: Risk[]): number[][] {
  const grid = Array.from({ length: 5 }, () => Array(5).fill(0) as number[]);
  for (const r of risks) {
    if (r.status === "controlled") continue;
    grid[clampScale(r.impact) - 1][clampScale(r.probability) - 1]++;
  }
  return grid;
}

export function sortRisks(risks: Risk[]): Risk[] {
  const rank = (r: Risk) => (r.status === "controlled" ? 1 : 0);
  return [...risks].sort((a, b) => rank(a) - rank(b) || riskScore(b) - riskScore(a) || b.updatedAt.localeCompare(a.updatedAt));
}

/** Следующая дата проверки после сохранения или отметки «проверил». */
export function nextReviewAt(r: Pick<Risk, "status" | "reviewEveryDays">, now: Date): string | undefined {
  return r.status === "controlled" ? undefined : dateInDays(now, clampPeriod(r.reviewEveryDays));
}


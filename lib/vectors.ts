export function determineVector(answers: VectorId[]): VectorProfile {
  const scores = new Map<VectorId, number>();
  for (const a of answers) {
    scores.set(a, (scores.get(a) ?? 0) + 1);
  }
  let best: VectorId = answers[0] ?? "sage";
  let bestScore = -1;
  for (const v of VECTORS) {
    const s = scores.get(v.id) ?? 0;
    if (s > bestScore) {
      bestScore = s;
      best = v.id;
    }
  }
  return getVector(best);
}
